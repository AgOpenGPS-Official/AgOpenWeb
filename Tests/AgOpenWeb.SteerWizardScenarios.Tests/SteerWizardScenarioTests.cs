namespace AgOpenWeb.SteerWizardScenarios.Tests;

/// <summary>
/// The steer wizard, end to end, with two operators: one who does everything right and one
/// who does everything wrong. Writes a markdown report (AGOPENWEB_SCENARIO_REPORT, default
/// steer-wizard-report.md in the test folder). The test fails only on a Safety finding or a
/// harness fault; every other finding is for the report.
/// </summary>
[TestFixture]
[Category("Scenario")]
[NonParallelizable]
public class SteerWizardScenarioTests
{
    private static string? Only => Environment.GetEnvironmentVariable("AGOPENWEB_SCENARIO_ONLY");

    [Test]
    public async Task Careful_and_careless_operators()
    {
        var journal = new ScenarioJournal();
        foreach (var (name, run) in Scenarios())
        {
            if (Only is { Length: > 0 } o && !o.Split('|').Any(x => name.Contains(x, StringComparison.OrdinalIgnoreCase))) continue;
            TestContext.Progress.WriteLine("scenario: " + name);
            await run(journal, name);
        }
        var path = ReportPath.For("steer-wizard-report.md");
        File.WriteAllText(path, journal.ToMarkdown("Steer wizard scenarios",
            "Every step of the steer wizard driven by a careful and a careless operator against an emulated AiO v4 steer module and a moving tractor. Generated by Tests/AgOpenWeb.SteerWizardScenarios.Tests."));
        TestContext.Progress.WriteLine("report: " + path);
        var safety = journal.Findings.Values.Where(v => v.First.Severity == Severity.Safety).Select(v => v.First.Code).ToList();
        var harness = journal.Findings.Values.Where(v => v.First.Code.StartsWith("HARNESS_", StringComparison.Ordinal)).Select(v => v.First.Message).ToList();
        Assert.Multiple(() =>
        {
            Assert.That(harness, Is.Empty, "harness faults");
            Assert.That(safety, Is.Empty, "safety findings (see the report)");
        });
    }

    internal static IEnumerable<(string Name, Func<ScenarioJournal, string, Task> Run)> Scenarios()
    {
        yield return ("Careful: whole wizard", (j, n) => CarefulOperator.RunAsync(j, n));
        foreach (var c in CarelessOperator.All())
            yield return c;
        foreach (var t in TuneScenarios.All())
            yield return t;
    }
}
