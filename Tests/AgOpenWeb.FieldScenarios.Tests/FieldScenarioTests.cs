namespace AgOpenWeb.FieldScenarios.Tests;

/// <summary>
/// The two operators on Renato's five fields. One backend for the whole run (like a day in
/// the cab: field after field without restarting the app), so state that leaks from one
/// field into the next is found too.
///
/// Environment:
///   AGOPENWEB_SCENARIO_REPORT=path.md   where to write the report (default: test folder)
///   AGOPENWEB_SCENARIO_ONLY=Olival      only fields whose name contains this
///   AGOPENWEB_SCENARIO_VERBOSE=1        every step to the test output
///
/// The tests fail only when the harness itself breaks, a step throws, or the host hangs;
/// the findings are the product, written to the report (the app has known open findings,
/// listed there, and failing CI on them would hide new ones).
/// </summary>
[TestFixture, Category("Scenario"), NonParallelizable]
public class FieldScenarioTests
{
    private FieldScenarioRig _rig = null!;
    private readonly ScenarioJournal _journal = new();
    private static string? Only => Environment.GetEnvironmentVariable("AGOPENWEB_SCENARIO_ONLY");

    [OneTimeSetUp]
    public async Task Boot()
    {
        var root = Path.Combine(Path.GetTempPath(), "aow-field-scenarios-" + DateTime.UtcNow.ToString("yyyyMMdd-HHmmss", System.Globalization.CultureInfo.InvariantCulture));
        _rig = await FieldScenarioRig.StartAsync(root);
        var setup = new Scenario(_rig, _journal, "Set-up", "careful");
        await setup.Step("tool: 8 sections of 1 m (Renato's sprayer)", () => new SetUp(setup).SetUpSprayer());
        TestContext.Out.WriteLine("data root: " + root);
    }

    [OneTimeTearDown]
    public async Task WriteReport()
    {
        var path = ReportPath.For("field-scenarios-report.md");
        var md = _journal.ToMarkdown("Field scenarios: the careful and the careless operator",
            "Generated by Tests/AgOpenWeb.FieldScenarios.Tests. Every step is a command the web client sends; " +
            "after each one the field state is checked against the rules in FieldInvariants.cs. " +
            "A finding is listed once, at the step that caused it; ×N counts how often it came back.");
        await File.WriteAllTextAsync(path, md);
        TestContext.Out.WriteLine("report: " + path);
        await _rig.DisposeAsync();
    }

    private static IEnumerable<(ScenarioField Field, BoundaryMethod Method)> Plan()
    {
        var methods = new Dictionary<string, BoundaryMethod>
        {
            ["Olival"] = BoundaryMethod.DrawOnMap,
            ["Baetas"] = BoundaryMethod.KmlNewField,
            ["Couto Ribeira"] = BoundaryMethod.DriveAround,
            ["Tapada da Casa"] = BoundaryMethod.KmlIntoOpenField,
            ["Quinta Torta"] = BoundaryMethod.DrawOnMap,
        };
        foreach (var f in ScenarioFields.All)
            if (Only == null || f.Name.Contains(Only, StringComparison.OrdinalIgnoreCase))
                yield return (f, methods.GetValueOrDefault(f.Name, BoundaryMethod.DrawOnMap));
    }

    [Test, Order(1)]
    public async Task The_careful_operator_builds_every_field()
    {
        foreach (var (field, method) in Plan())
        {
            var s = new Scenario(_rig, _journal, field.Name + " (" + method + ")", "careful");
            await new GoodOperator(s, field, method, field.Name).Run();
        }
        AssertNoHarnessFailure();
    }

    [Test, Order(2)]
    public async Task The_careless_operator_does_everything_wrong()
    {
        // The careless operator works on one real field (the first in the plan) and makes
        // small throw-away fields of its own; the careful operator's fields stay as built.
        var field = Plan().First().Field;
        var s = new Scenario(_rig, _journal, "Careless on " + field.Name, "careless");
        await new BadOperator(s, field).Run();
        AssertNoHarnessFailure();
    }

    private void AssertNoHarnessFailure()
    {
        var broken = _journal.Findings.Values.Where(v => v.First.Code is "HARNESS" or "HANG").ToList();
        Assert.That(broken, Is.Empty, string.Join("\n", broken.Select(b => b.First.Message + " @ " + b.Where)));
    }

    private sealed class SetUp(Scenario s) : Operator(s);
}
